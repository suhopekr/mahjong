// game, Settings, Close, Sound, Language, Your games, You won!, …).
//
// English is the source. The translator adds `es`, `pt`, `fr`, `it`, `de`,
// `ru`, `tr`, `id`, `ko`, `ja`, `zh`, `zh-Hant`, `ar` beside it with the
// same keys in the same order (test/strings.test.js checks the key sets
// match). Values are strings, or functions of one object for phrases that
// carry a name or a count — the argument names are fixed:
//
//   pickedUp({ name })            name: a card name from cardName()
//   cannotGoPile({ name })
//   cannotGoColumn({ name })
//   nowhere({ name })
//   won({ moves })                moves: a number
//   hintToFoundation({ name })
//   hintToEmpty({ name })
//   hintOnto({ name, target })    target: another card name
//   cardName({ rank, suit })      rank: rank1..rank13, suit: suitS/H/D/C
//
// Card faces keep the international A J Q K indices — rank1..rank13 are
// only what is *said* (status line, screen readers), so a language may
// spell them out ("Ace", "Bube") without touching the cards.
//
// The long-form page text (intro, How to Play, FAQ) and the JSON-LD stay
// English in index.html on purpose — they are the SEO text.
