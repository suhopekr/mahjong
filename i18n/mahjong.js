// /i18n/mahjong.js — the words the Mahjong board itself says.
//
// Mahjong and the Daily Challenge run on `game.js`, a 3,000-line classic
// script that predates every module on the site. Everything else a visitor
// reads on those two pages was already translated — the top bar, the footer,
// the article below the board — and the board in the middle of it stayed in
// English in all thirteen languages: "Pairs: 7", "Time: 00:03", Undo, Hint,
// Menu, Settings top to bottom, every modal. This file is that gap closed.
//
// It is the same shape as any game's src/i18n/strings.js — { en: {...}, ko:
// {...} } — and is handed to createI18n() by /mahjong-i18n.js, the small
// module that bridges the module world to `game.js`'s global one.
//
// What is NOT here: anything /i18n/common.js already has (hint, undo,
// newGame, settings, close, sound, gamesPlayed, gamesWon, keepPlaying,
// startNewQ, putAway, advertisement, skipToBoard) — the lookup chain falls
// through to common, so a word that every game shares is defined once. And
// the long-form article below the board, which is SEO copy and works the
// other way round entirely (/i18n/pages/index.js, /i18n/pages/daily.js).
//
// Two conventions worth knowing before you translate:
//
//   `**bold**`  in the install-hint strings is the only markup allowed. It
//               marks the words a person has to LOOK FOR on their own phone
//               ("Share", "Add to Home Screen") — those are the names of
//               real menu items, so translate them to whatever the phone
//               itself says in that language, and keep the ** around them.
//               game.js turns them into <strong> nodes, never innerHTML.
//
//   monthNames / weekdayLetters are ARRAYS, not strings: 12 months starting
//               January, then 7 weekday initials starting SUNDAY. The
//               weekday cells are one character wide — use the shortest
//               form the language has (日 月 火…, 일 월 화…, S M T…).
